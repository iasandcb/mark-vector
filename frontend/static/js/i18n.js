// Reverse lookup for "## User"/"## Assistant"-equivalent headings: given a
// line of text, which role (if any) it marks - checked against all three
// languages' `chat.userHeading`/`chat.assistantHeading` regardless of the
// *current* language, since one document's rounds can be sent under
// different UI languages over time (app.js's isIncompleteExchange/
// splitPendingQuestion rely on this). Mirrors backend/app/storage.py's
// EXCHANGE_HEADINGS/_EXCHANGE_HEADING_ROLES - keep both in sync if either
// changes.
const EXCHANGE_HEADING_ROLES = {};
for (const lang of SUPPORTED) {
  EXCHANGE_HEADING_ROLES[DICT[lang]["chat.userHeading"]] = "user";
  EXCHANGE_HEADING_ROLES[DICT[lang]["chat.assistantHeading"]] = "assistant";
}

export function exchangeHeadingRole(line) {
  return EXCHANGE_HEADING_ROLES[line] || null;
}

function readStoredLang() {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return SUPPORTED.includes(v) ? v : null;
  } catch (err) {
    return null;
  }
}

// Deliberately NOT navigator.language-based - "기본은 영어" (default is
// English) means the fallback before any explicit choice is always English,
// not whatever the browser happens to be set to. A stored choice always
// wins once one exists.
let currentLang = readStoredLang() || DEFAULT_LANG;
document.documentElement.lang = currentLang;

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  if (!SUPPORTED.includes(lang) || lang === currentLang) return;
  currentLang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch (err) {
    // localStorage unavailable - the choice just won't persist across reloads
  }
  document.documentElement.lang = lang;
}

export function t(key, vars) {
  let text = DICT[currentLang]?.[key];
  if (text === undefined) text = DICT[DEFAULT_LANG][key];
  if (text === undefined) return key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, value);
    }
  }
  return text;
}

// Translates static markup: `data-i18n` -> textContent, `data-i18n-title`
// -> title, `data-i18n-placeholder` -> placeholder. Anything built
// dynamically (tree rows, alerts, ...) calls t() directly instead - this is
// only for what's already sitting in the HTML at load time.
export function applyStaticTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
}

// Builds a <select> for the caller to insert anywhere in the page chrome.
// Changing it reloads the page - see the module doc-comment for why that's
// the deliberate choice instead of a live re-render.
export function createLanguageSelect() {
  const select = document.createElement("select");
  select.className = "lang-select";
  select.title = t("ui.language");
  for (const lang of SUPPORTED) {
    const opt = document.createElement("option");
    opt.value = lang;
    opt.textContent = LANG_LABELS[lang];
    if (lang === currentLang) opt.selected = true;
    select.appendChild(opt);
  }
  select.addEventListener("change", () => {
    setLanguage(select.value);
    location.reload();
  });
  return select;
}
