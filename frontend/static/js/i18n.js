// Minimal, dependency-free i18n: a flat key -> string dictionary per
// language, a `t(key, vars)` lookup with `{var}` interpolation, and a
// `data-i18n*` attribute scanner for static markup. No per-page bundling or
// build step - every page (index.html/app.js, public.html/public.js,
// login.html) imports this same module and shares one dictionary, so a
// string used in more than one place (the PDF export tooltip, the "unsaved
// changes" confirm) is translated once, not duplicated per page.
//
// Language selection is a plain user preference, not content negotiation:
// default is English regardless of browser locale, and only changes when
// the user explicitly picks one from createLanguageSelect()'s dropdown
// (persisted to localStorage from then on). There's no live re-render path
// for a language change - createLanguageSelect() reloads the page instead,
// which is simplest and correct by construction (every label, tree row, and
// alert already renders from `t()` on a fresh load; teaching every dynamic
// render function to redraw in place would be a lot of surface for a rare
// action).

